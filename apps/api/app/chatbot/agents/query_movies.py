def query_dataset_movies(
    title: str = "",
    director: str = "",
    actors: Optional[List[str]] = None,
    genres: Optional[List[str]] = None,
    year: str = "",
    min_rating: Optional[float] = None,
    keywords: Optional[List[str]] = None,
    limit: int = 30
) -> List[Dict[str, Any]]:
    """
    Query PostgreSQL across all dataset dimensions:
    title, director, actors, genres, release year/decade, min rating, keywords.
    """
    conn = None
    try:
        conn = get_db_connection()
        cur = conn.cursor()

        where_clauses = []
        params = []

        if title and title.strip():
            where_clauses.append("m.title ILIKE %s")
            params.append(f"%{title.strip()}%")

        if director and director.strip():
            where_clauses.append("d.name ILIKE %s")
            params.append(f"%{director.strip()}%")

        if actors:
            for actor in actors:
                if actor.strip():
                    where_clauses.append("a.name ILIKE %s")
                    params.append(f"%{actor.strip()}%")

        if genres:
            for g in genres:
                if g.strip() and g.strip().lower() != "all":
                    where_clauses.append("g.name ILIKE %s")
                    params.append(f"%{g.strip()}%")

        if year and year.strip() and year.strip().lower() != "all":
            y = year.strip()
            if len(y) == 4 and y.isdigit():
                where_clauses.append("m.release_date LIKE %s")
                params.append(f"{y}%")
            elif y in ("2010s", "2010"):
                where_clauses.append("m.release_date >= '2010' AND m.release_date <= '2019-12-31'")
            elif y in ("2020s", "2020"):
                where_clauses.append("m.release_date >= '2020'")
            elif y in ("2000s", "2000"):
                where_clauses.append("m.release_date >= '2000' AND m.release_date <= '2009-12-31'")
            elif y == "classic":
                where_clauses.append("m.release_date < '2000' AND m.release_date != ''")
            elif "-" in y:
                parts = y.split("-")
                if len(parts) == 2 and parts[0].isdigit() and parts[1].isdigit():
                    where_clauses.append("m.release_date >= %s AND m.release_date <= %s")
                    params.extend([f"{parts[0]}-01-01", f"{parts[1]}-12-31"])

        if min_rating is not None and min_rating > 0:
            where_clauses.append("m.vote_average >= %s")
            params.append(min_rating)

        if keywords:
            for kw in keywords:
                if kw.strip():
                    where_clauses.append("t.name ILIKE %s")
                    params.append(f"%{kw.strip()}%")

        where_sql = ("WHERE " + " AND ".join(where_clauses)) if where_clauses else ""

        query = f"""
            WITH matched AS (
                SELECT m.movieid
                FROM movies m
                LEFT JOIN directors d ON m.director_id = d.id
                LEFT JOIN movie_genres mg ON m.movieid = mg.movie_id
                LEFT JOIN genres g ON mg.genre_id = g.id
                LEFT JOIN movie_actors ma ON m.movieid = ma.movie_id
                LEFT JOIN actors a ON ma.actor_id = a.id
                LEFT JOIN movie_tags mt ON m.movieid = mt.movie_id
                LEFT JOIN tags t ON mt.tag_id = t.id
                {where_sql}
                GROUP BY m.movieid
                LIMIT %s
            )
            SELECT 
                m.movieid AS "movieId", 
                m.title, 
                m.release_date, 
                m.popularity, 
                m.adult, 
                m.overview, 
                m.vote_average, 
                m.vote_count, 
                m.poster_url,
                d.name AS director,
                COALESCE(STRING_AGG(DISTINCT g.name, '|'), '') AS genres,
                COALESCE(STRING_AGG(DISTINCT a.name, '|'), '') AS cast,
                COALESCE(STRING_AGG(DISTINCT t.name, '|'), '') AS keywords
            FROM matched mat
            JOIN movies m ON mat.movieid = m.movieid
            LEFT JOIN directors d ON m.director_id = d.id
            LEFT JOIN movie_genres mg ON m.movieid = mg.movie_id
            LEFT JOIN genres g ON mg.genre_id = g.id
            LEFT JOIN movie_actors ma ON m.movieid = ma.movie_id
            LEFT JOIN actors a ON ma.actor_id = a.id
            LEFT JOIN movie_tags mt ON m.movieid = mt.movie_id
            LEFT JOIN tags t ON mt.tag_id = t.id
            GROUP BY m.movieid, m.title, m.release_date, m.popularity, m.adult, m.overview, m.vote_average, m.vote_count, m.poster_url, d.name
            ORDER BY m.popularity DESC, m.vote_average DESC
        """
        params.append(limit)
        cur.execute(query, tuple(params))
        rows = [dict(r) for r in cur.fetchall()]
        cur.close()
        return rows
    except Exception as e:
        logger.warning(f"query_dataset_movies error: {e}")
        return []
    finally:
        if conn:
            conn.close()


def query_movies_node(state: GraphState) -> dict:
    """
    Retrieve candidate movies and facts:
    1. Check for 'more_recommendations' request -> fetch next slice from RecSys session pool.
    2. SQL Database Retrieval for factual/catalog queries.
    3. Multi-field dataset query + RecSys ranking across Title, Year, Director, Cast, Genres, Rating.
    4. Save full pool of RecSys recommendations to session memory for subsequent requests.
    """
    intent_output = state.get("intent_output")
    intent = intent_output.intent if intent_output else "fallback"
    target = intent_output.target_title.strip() if intent_output and intent_output.target_title else ""
    genres = intent_output.genres or [] if intent_output else []
    director = intent_output.director.strip() if intent_output and intent_output.director else ""
    actors = intent_output.actors or [] if intent_output else []
    year = intent_output.year.strip() if intent_output and intent_output.year else ""
    min_rating = intent_output.min_rating if intent_output else None
    keywords = intent_output.keywords or [] if intent_output else []
    is_more_req = intent_output.is_more_request if intent_output else False

    session_id = state.get("session_id") or "default"
    user_id = state.get("user_id")
    user_liked_ids = state.get("user_liked_ids") or []
    messages = state.get("messages", [])
    last_user_msg = messages[-1].content if messages else ""

    candidates: list[dict[str, Any]] = []
    matched: dict[str, Any] | None = None
    sql_query_text: str | None = None
    sql_results_data: list[dict[str, Any]] | None = None
    sql_message_text: str | None = None

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 1: USER REQUESTS MORE RECOMMENDATIONS FROM PREVIOUS POOL
    # ─────────────────────────────────────────────────────────────────────────
    if is_more_req or intent == "more_recommendations":
        next_batch = get_next_recsys_batch(session_id, batch_size=5)
        if next_batch:
            logger.info(f"Retrieved {len(next_batch)} next movies from RecSys pool for session {session_id}")
            return {
                "candidate_movies": next_batch,
                "matched_movie": None,
                "sql_query": None,
                "sql_results": None,
                "sql_message": None
            }

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 2: SQL QUERY INTENT (Direct Factual Lookups, Counts, Watchlist)
    # ─────────────────────────────────────────────────────────────────────────
    if intent == "sql_query":
        conv_summary = " ".join([m.content for m in messages[-4:]]) if len(messages) > 1 else ""
        sql_res = SQLRetriever.query(
            user_query=last_user_msg,
            conversation_summary=conv_summary,
            user_id=user_id
        )
        sql_query_text = sql_res.get("sql")
        sql_results_data = sql_res.get("rows")
        sql_message_text = sql_res.get("message")

        if sql_res.get("movie_cards"):
            candidates = sql_res["movie_cards"]

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 2.5: MOVIE DETAIL INTENT (Lookup specific movie details & info)
    # ─────────────────────────────────────────────────────────────────────────
    elif intent == "movie_detail" or (target and any(k in last_user_msg.lower() for k in ["chi tiết", "thông tin", "nội dung", "giới thiệu", "review", "về phim", "about"])):
        search_query = target or last_user_msg
        try:
            detail_results = MovieModel.search_with_filters(query_str=search_query, limit=5)
            if detail_results:
                matched = detail_results[0]
                candidates = [matched]
                # Also include 2-3 similar movies as candidate cards for recommendations
                mid = matched.get("movieId") or matched.get("movieid")
                if mid:
                    similar = RecsysService.get_similar_movies(int(mid), limit=5)
                    if similar:
                        for sm in similar:
                            sm_id = sm.get("movieId") or sm.get("movieid")
                            if sm_id != mid and sm not in candidates:
                                candidates.append(sm)
                                if len(candidates) >= 4:
                                    break
                save_recsys_pool(session_id, candidates, initial_count=len(candidates))
        except Exception as e:
            logger.warning(f"Movie detail search failed: {e}")

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 3: SIMILAR MOVIE INTENT
    # ─────────────────────────────────────────────────────────────────────────
    elif (intent == "similar" or "similar" in intent) and target:
        try:
            results = MovieModel.search_with_filters(query_str=target, limit=5)
            if results:
                matched = results[0]
                movie_id = matched.get("movieId") or matched.get("movieid")
                if movie_id:
                    similar = RecsysService.get_similar_movies(int(movie_id), limit=25)
                    if similar:
                        save_recsys_pool(session_id, similar, initial_count=5)
                        candidates = similar[:5]
        except Exception as e:
            logger.warning(f"Similar movies search failed: {e}")

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 4: SEARCH FILTER ACROSS DATASET FIELDS (Year, Director, Cast, Rating, Multi-filter)
    # ─────────────────────────────────────────────────────────────────────────
    elif intent in ("search_filter", "year", "director", "actor", "rating") or director or actors or year or min_rating:
        try:
            filter_results = query_dataset_movies(
                title=target,
                director=director,
                actors=actors,
                genres=genres,
                year=year,
                min_rating=min_rating,
                keywords=keywords,
                limit=30
            )
            if filter_results:
                # Rank results using RecSys / Popularity & Rating
                save_recsys_pool(session_id, filter_results, initial_count=5)
                candidates = filter_results[:5]
        except Exception as e:
            logger.warning(f"Dataset filter query failed: {e}")

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 5: PERSONALIZED RECOMMENDATION INTENT
    # ─────────────────────────────────────────────────────────────────────────
    elif (intent == "personalized" or "personal" in intent or "recommend" in intent) and not candidates:
        try:
            recs = []
            if user_id:
                recs = RecsysService.get_user_recommendations(user_id=user_id, limit=25)
            elif user_liked_ids:
                recs = RecsysService.get_personalized_recommendations(user_liked_ids, limit=25)
            else:
                recs = MovieModel.get_trending(page=1, limit=25)

            if recs:
                save_recsys_pool(session_id, recs, initial_count=5)
                candidates = recs[:5]
        except Exception as e:
            logger.warning(f"Personalized recommendation failed: {e}")

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 6: GENRE INTENT
    # ─────────────────────────────────────────────────────────────────────────
    elif intent == "genre" and genres:
        try:
            seen_ids = set()
            pool = []
            for g in genres:
                results = MovieModel.get_movie_by_genre(g.strip().lower(), page=1, limit=15)
                for m in results:
                    mid = m.get("movieId") or m.get("movieid")
                    if mid and mid not in seen_ids:
                        seen_ids.add(mid)
                        pool.append(m)
            if pool:
                save_recsys_pool(session_id, pool, initial_count=5)
                candidates = pool[:5]
        except Exception as e:
            logger.warning(f"Genre movie query failed: {e}")

    # ─────────────────────────────────────────────────────────────────────────
    # CASE 7: KEYWORD / GENERAL FALLBACK QUERY
    # ─────────────────────────────────────────────────────────────────────────
    if not candidates and last_user_msg and len(last_user_msg.strip()) > 2 and intent != "general_qa":
        try:
            search_res = MovieModel.search_with_filters(query_str=last_user_msg, limit=20)
            if search_res:
                matched = search_res[0]
                save_recsys_pool(session_id, search_res, initial_count=5)
                candidates = search_res[:5]
        except Exception as e:
            logger.debug(f"Keyword search bypassed: {e}")

    # Ensure matched_movie is populated whenever target_title is present
    if not matched and target:
        try:
            res = MovieModel.search_with_filters(query_str=target, limit=3)
            if res:
                matched = res[0]
                if not candidates:
                    candidates = [matched]
        except Exception as e:
            logger.debug(f"Target fallback lookup bypassed: {e}")

    return {
        "candidate_movies": candidates,
        "matched_movie": matched,
        "sql_query": sql_query_text,
        "sql_results": sql_results_data,
        "sql_message": sql_message_text
    }