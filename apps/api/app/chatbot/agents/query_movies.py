logger = logging.getLogger(__name__)

# In-memory recsys session pool cache (fallback when Redis is not available)
_in_memory_recsys_pools: Dict[str, Dict[str, Any]] = {}


def save_recsys_pool(session_id: str, all_movies: List[Dict[str, Any]], initial_count: int = 5):
    """
    Saves the full list of recommendations generated by RecSys for this session,
    enabling subsequent retrieval of the next batch when user asks for more.
    """
    if not session_id or not all_movies:
        return
    data = {
        "all_movies": all_movies,
        "offset": initial_count,
        "page_size": initial_count,
    }
    _in_memory_recsys_pools[session_id] = data
    r = get_redis_client()
    if r:
        try:
            r.set(f"chat:{session_id}:recsys_pool", json.dumps(data, default=str), ex=86400)
        except Exception as e:
            logger.debug(f"Redis recsys pool save failed: {e}")


def get_next_recsys_batch(session_id: str, batch_size: int = 5) -> List[Dict[str, Any]]:
    """
    Retrieves the next batch of recommended movies from the saved RecSys pool for this session.
    """
    if not session_id:
        return []
    data = None
    r = get_redis_client()
    if r:
        try:
            raw = r.get(f"chat:{session_id}:recsys_pool")
            if raw:
                data = json.loads(raw)
        except Exception as e:
            logger.debug(f"Redis recsys pool get failed: {e}")

    if not data:
        data = _in_memory_recsys_pools.get(session_id)
    if not data:
        return []

    all_movies = data.get("all_movies", [])
    offset = data.get("offset", 0)
    if offset >= len(all_movies):
        return []

    next_batch = all_movies[offset:offset + batch_size]
    data["offset"] = offset + len(next_batch)
    _in_memory_recsys_pools[session_id] = data
    if r:
        try:
            r.set(f"chat:{session_id}:recsys_pool", json.dumps(data, default=str), ex=86400)
        except Exception:
            pass
    return next_batch


